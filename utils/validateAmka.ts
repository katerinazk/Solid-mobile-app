// Επικυρώνει μόνο τη μορφή ενός ΑΜΚΑ: ακριβώς 11 ψηφία. Δεν ελέγχει checksum ούτε αν τα πρώτα
// ψηφία σχηματίζουν πραγματική ημερομηνία γέννησης - πιάνει μόνο προφανή τυπογραφικά λάθη
// (λάθος αριθμός ψηφίων, γράμματα).
export function isValidAmka(value: string): boolean {
  const digits = value.trim();
  return /^\d{11}$/.test(digits);
}
